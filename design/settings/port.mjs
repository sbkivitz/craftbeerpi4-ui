// Make the Settings mockup (design/settings) into the Settings page's own files, untouched where they can be:
//
//   node design/settings/port.mjs
//
// It writes, under cbpi4gui/src/components/settings:
//
// - catalog.js: the mockup's two tables, M (what the page knows about each setting) and G (the nine groups), with
//   PLUGIN, PLUGIN_ORDER and ELSEWHERE, as they are in settings.js. M names temperatures in TEMP_UNIT, so it comes
//   from catalog(F): F is true when TEMP_UNIT is °F.
// - demo-data.js: settings-data.js (the simulator's settings, read once), for ?demo=, as CFG and THINGS.
// - settings.css: the page's own rules, for its shadow root. The page draws inside a shadow root so the brew-day
//   screen's rules for .plate, .seg, .note, .st and the rest (the same names, other things) can't reach it, and its
//   rules can't reach the title bar. So :root becomes :host, the frame's rules (title bar, last event, tabs: the
//   brew-day screen's own, which it draws) are left out, and so are .app's, which go in settings-frame.css.
// - settings-frame.css: the mockup's .app rules (one screen tall from 620 px, not the brew-day's 860; scrolling below
//   1180 px wide; room for the phone's save bar), for <html data-page=settings> only.
//
// The stylesheets are kept as text (config-overrides.js), as the brew-day screen's are: the CSS pipeline would
// rewrite them.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "..", "cbpi4gui", "src", "components", "settings");
const HEAD = "// Generated by design/settings/port.mjs from the Settings mockup (design/settings). Don't edit by hand: change the\n"
  + "// mockup and run it again.\n";
const crlf = s => s.replace(/\r\n/g, "\n");
const read = f => crlf(readFileSync(join(here, f), "utf8"));
const fail = msg => { throw new Error(`port.mjs: ${msg} - has the mockup's shape changed?`); };
function between(s, start, end) {
  const i = s.indexOf(start);
  if (i < 0) fail(`no ${JSON.stringify(start)}`);
  const j = s.indexOf(end, i + start.length);
  if (j < 0) fail(`no ${JSON.stringify(end)} after ${JSON.stringify(start)}`);
  return s.slice(i, j);
}
const write = (name, text) => { writeFileSync(join(OUT, name), text); console.log(`wrote ${join(OUT, name)}`); };

/* ---------- catalog.js ---------- */
{
  const js = read("settings.js");
  const deg = between(js, "const F = ", "\n");
  if (!/^const F = String\(\(CFG\.TEMP_UNIT/.test(deg)) fail("F isn't read from TEMP_UNIT");
  const degLine = between(js, "const DEG = ", "\n");
  const M = between(js, "const M = {", "\n};\n") + "\n};";
  const G = between(js, "const G = [", "\n];\n") + "\n];";
  const plugin = between(js, "const PLUGIN = ", "\n");
  const order = between(js, "const PLUGIN_ORDER = ", "\n");
  const elsewhere = between(js, "const ELSEWHERE = ", "\n");
  const ind = s => s.split("\n").map(l => l ? "  " + l : l).join("\n");
  write("catalog.js", `${HEAD}//
// The page's catalogue, kept in the web page: M, what it knows about each setting - its plain
// name n, what it does h, extra words for FIND syn, its control ctl, option order and labels, what blank means,
// unit, restart, its main switch dep, adv, secret, InfluxDB Cloud's names cloud and hc, a worked-out line calc, keep -
// and G, the nine groups in brewing order. A setting it doesn't list still shows, by its key (page.js).

/* M, for a page whose TEMP_UNIT is °F (F true) or °C */
export function catalog(F) {
${ind(degLine)}
${ind(M)}
  return M;
}
/* the groups, in brewing order; a see-also line names a setting that lives in another group but matters here */
export ${G}
export ${plugin}
export ${order}
/* words that belong to settings kept elsewhere, for FIND when nothing here matches */
export ${elsewhere}
`);
}

/* ---------- demo-data.js ---------- */
{
  let d = read("settings-data.js");
  const n = (d.match(/^window\.\w+ = /gm) || []).length;
  d = d.replace(/^window\.CBPI_CONFIG = /m, "export const CFG = ").replace(/^window\.CBPI_THINGS = /m, "export const THINGS = ");
  if (n !== 2 || /^window\./m.test(d)) fail("settings-data.js should set exactly window.CBPI_CONFIG and window.CBPI_THINGS");
  write("demo-data.js", `${HEAD}${d.endsWith("\n") ? d : d + "\n"}`);
}

/* ---------- settings.css and settings-frame.css ---------- */
{
  const css = read("settings.css");
  const FRAME = "/* ---------- the frame:", OWN = "/* ---------- settings ---------- */";
  const base = css.slice(0, css.indexOf(FRAME));
  const frame = between(css, FRAME, OWN);
  const own = css.slice(css.indexOf(OWN));
  if (css.indexOf(FRAME) < 0 || css.indexOf(OWN) < 0) fail("no frame or settings section");

  // the rules of a piece of CSS, at the top level or in one @media: [{media, sel, body}]
  function rules(text) {
    const out = [], s = text.replace(/\/\*[\s\S]*?\*\//g, "");
    let i = 0;
    const block = (from, media) => {
      let k = from;
      while (k < s.length) {
        const open = s.indexOf("{", k), close = s.indexOf("}", k);
        if (close >= 0 && (open < 0 || close < open)) return close + 1;
        if (open < 0) return s.length;
        const sel = s.slice(k, open).trim();
        if (sel.startsWith("@media") || sel.startsWith("@supports")) { k = block(open + 1, sel); continue; }
        if (sel.startsWith("@keyframes")) {
          let depth = 1, p = open + 1;
          while (depth && p < s.length) { if (s[p] === "{") depth++; else if (s[p] === "}") depth--; p++; }
          out.push({media, sel, body: s.slice(open + 1, p - 1), raw: true});
          k = p; continue;
        }
        const end = s.indexOf("}", open);
        out.push({media, sel, body: s.slice(open + 1, end)});
        k = end + 1;
      }
      return k;
    };
    while (i < s.length) i = block(i, null) || s.length;
    return out;
  }
  const emit = list => {
    let out = "", m = null;
    for (const r of list) {
      if (r.media !== m) { if (m) out += "}\n"; if (r.media) out += `${r.media}{\n`; m = r.media; }
      out += `${r.sel}{${r.body}}\n`;
    }
    if (m) out += "}\n";
    return out;
  };
  const sels = sel => sel.split(",").map(x => x.trim());
  // the frame's elements: the brew-day screen draws them, with its own rules. The mockup writes layout B's under
  // [data-layout=b], as the brew-day mockup does, some of them in its own section's @media blocks
  const LAYOUT = /^(html)?\[data-layout=b\]\s+/;
  const FRAME_EL = /^(\.app\b|\.topbar\b|\.banner\b|\.brand\b|#link-t\b|\.link\b|\.clock\b|\.alloff\b|\.event\b|\.status\b|\.tabs\b|\.toast\b|\.res\b|\.logbtn\b)/;
  const isFrame = x => FRAME_EL.test(x.replace(LAYOUT, ""));
  const isApp = sel => sels(sel).every(x => /^\.app\b/.test(x));

  const shadow = [], outer = [];
  // base: the page's element defaults, which a shadow root doesn't get from the document
  for (const r of rules(base)) {
    if (r.sel.startsWith(".mock") || r.sel.startsWith("html.bare") || r.sel === "body" || r.sel === "html") {
      if (r.sel === "html") shadow.push({media: r.media, sel: ":host", body: "color-scheme:dark"});
      continue;
    }
    if (r.sel === ":root") { shadow.push({...r, sel: ":host", body: r.body.replace(/--mock-h:[^;]*;?/, "").replace(/;$/, "")}); continue; }
    shadow.push(r);
  }
  for (const r of rules(frame)) if (isApp(r.sel)) outer.push(r);
  for (const r of rules(own)) {
    if (r.raw) { shadow.push(r); continue; }
    if (r.sel === ":root") { shadow.push({...r, sel: ":host"}); continue; }
    if (isApp(r.sel)) { outer.push(r); continue; }
    const keep = sels(r.sel).filter(x => !isFrame(x));
    if (!keep.length) continue;
    shadow.push({...r, sel: keep.join(",")});
  }
  // the host fills the frame's fourth row, and the page's .main fills the host
  shadow.unshift({media: null, sel: ":host", body: "display:grid;grid-template-columns:minmax(0,1fr);grid-template-rows:minmax(0,1fr);min-width:0;min-height:0"});
  const SCOPE = "html.bd-page[data-page=settings] ";
  const CHEAD = "/* Generated by design/settings/port.mjs from the Settings mockup (design/settings). Don't edit by hand: change the\n   mockup and run it again. */\n";
  write("settings.css", CHEAD + emit(shadow));
  write("settings-frame.css", CHEAD + emit(outer.map(r => ({...r, sel: sels(r.sel).map(x => SCOPE + x).join(",")}))));
}
