// Make the Hardware mockup (design/hardware) into the Hardware page's own files, untouched where they can be:
//
//   node design/hardware/port.mjs
//
// It writes, under cbpi4gui/src/components/hardware:
//
// - catalog.js: hardware-catalog.js as a module, exporting HW_OWN (the rows every kettle, probe and switch has),
//   HW_TYPES (each control's and part's plain names, lines, units and parts), HW_EMPTY (what the settings that mean
//   something when empty do then) and HW_SYN (extra words for FIND).
// - hardware.css: the page's own rules, for its shadow root. The page draws inside a shadow root so the brew-day
//   screen's rules for .plate, .seg, .note, .main and the rest (the same names, other things) can't reach it, and its
//   rules can't reach the title bar. So :root becomes :host, the frame's rules (title bar, last event, tabs: the
//   brew-day screen's own, which it draws) are left out, and so are .app's, which go in hardware-frame.css. The
//   drawing's rules (brew-day.css's own for layout B's line drawing) come along: the page draws its own copy of the
//   brewhouse in the shadow root.
// - hardware-frame.css: the mockup's .app rules (one screen tall from 620 px, not the brew-day's 860; scrolling below
//   1180 px wide; room for the phone's save bar), for <html data-page=hardware> only. And the name box's own rules:
//   input#name sits in the page's host, outside the shadow root, and shows in the Name row through a slot, so a
//   script reading the document finds it there. It takes the mockup's .fld (or, while the item hasn't arrived, .sr)
//   and :focus-visible rules.
//
// The stylesheets are kept as text (config-overrides.js), as the brew-day screen's are: the CSS pipeline would
// rewrite them.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "..", "cbpi4gui", "src", "components", "hardware");
const HEAD = "// Generated by design/hardware/port.mjs from the Hardware mockup (design/hardware). Don't edit by hand: change the\n"
  + "// mockup and run it again.\n";
const crlf = s => s.replace(/\r\n/g, "\n");
const read = f => crlf(readFileSync(join(here, f), "utf8"));
const fail = msg => { throw new Error(`port.mjs: ${msg} - has the mockup's shape changed?`); };
function between(s, start, end) {
  const i = s.indexOf(start);
  if (i < 0) fail(`no ${JSON.stringify(start)}`);
  const j = s.indexOf(end, i + start.length);
  if (j < 0) fail(`no ${JSON.stringify(end)} after ${JSON.stringify(start)}`);
  return s.slice(i, j);
}
const write = (name, text) => { writeFileSync(join(OUT, name), text); console.log(`wrote ${join(OUT, name)}`); };

/* ---------- catalog.js ---------- */
{
  let js = read("hardware-catalog.js");
  const NAMES = ["HW_OWN", "HW_TYPES", "HW_EMPTY", "HW_SYN"];
  js = js.replace(/^"use strict";\n/, "");
  for (const n of NAMES) {
    const re = new RegExp(`^const ${n} = `, "m");
    if (!re.test(js)) fail(`no const ${n}`);
    js = js.replace(re, `export const ${n} = `);
  }
  if (/^(const|let|var|function) /m.test(js)) fail("hardware-catalog.js has more than HW_OWN, HW_TYPES, HW_EMPTY and HW_SYN");
  write("catalog.js", `${HEAD}${js.endsWith("\n") ? js : js + "\n"}`);
}

/* ---------- hardware.css and hardware-frame.css ---------- */
{
  const css = read("hardware.css");
  const FRAME = "/* ---------- the frame:", DRAW = "/* ---------- the drawing:", OWN = "/* ---------- hardware ---------- */";
  if (css.indexOf(FRAME) < 0 || css.indexOf(DRAW) < 0 || css.indexOf(OWN) < 0) fail("no frame, drawing or hardware section");
  const base = css.slice(0, css.indexOf(FRAME));
  const frame = between(css, FRAME, DRAW);
  const draw = between(css, DRAW, OWN);
  const own = css.slice(css.indexOf(OWN));

  // the rules of a piece of CSS, at the top level or in @media, @supports and @container blocks, nested as they are:
  // [{media: [the blocks' preludes, outermost first], sel, body}]
  function rules(text) {
    const out = [], s = text.replace(/\/\*[\s\S]*?\*\//g, "");
    let i = 0;
    const block = (from, media) => {
      let k = from;
      while (k < s.length) {
        const open = s.indexOf("{", k), close = s.indexOf("}", k);
        if (close >= 0 && (open < 0 || close < open)) return close + 1;
        if (open < 0) return s.length;
        const sel = s.slice(k, open).trim();
        if (/^@(media|supports|container)\b/.test(sel)) { k = block(open + 1, [...media, sel]); continue; }
        if (sel.startsWith("@keyframes")) {
          let depth = 1, p = open + 1;
          while (depth && p < s.length) { if (s[p] === "{") depth++; else if (s[p] === "}") depth--; p++; }
          out.push({media, sel, body: s.slice(open + 1, p - 1), raw: true});
          k = p; continue;
        }
        const end = s.indexOf("}", open);
        out.push({media, sel, body: s.slice(open + 1, end)});
        k = end + 1;
      }
      return k;
    };
    while (i < s.length) i = block(i, []) || s.length;
    return out;
  }
  // the rules again as CSS, each block opened once for the rules in a row that share it
  const emit = list => {
    let out = "", open = [];
    for (const r of list) {
      let same = 0;
      while (same < open.length && same < r.media.length && open[same] === r.media[same]) same++;
      out += "}\n".repeat(open.length - same) + r.media.slice(same).map(m => `${m}{\n`).join("");
      open = r.media;
      out += `${r.sel}{${r.body}}\n`;
    }
    return out + "}\n".repeat(open.length);
  };
  const sels = sel => sel.split(",").map(x => x.trim());
  // the frame's elements: the brew-day screen draws them, with its own rules. The mockup writes layout B's under
  // [data-layout=b], as the brew-day mockup does, some of them in its own section's @media blocks
  const LAYOUT = /^(html)?\[data-layout=b\]\s+/;
  const FRAME_EL = /^(\.app\b|\.topbar\b|\.banner\b|\.brand\b|#link-t\b|\.link\b|\.clock\b|\.alloff\b|\.event\b|\.status\b|\.tabs\b|\.toast\b|\.res\b|\.logbtn\b)/;
  const isFrame = x => FRAME_EL.test(x.replace(LAYOUT, ""));
  const isApp = sel => sels(sel).every(x => /^\.app\b/.test(x));
  // the name box, in the host's light tree: these mockup rules are its own, under its own selectors
  const LIGHT = {".fld": "#name.fld", ".sr": "#name.sr", ":focus-visible": "#name:focus-visible"};

  const shadow = [], outer = [], light = [];
  // base: the page's element defaults, which a shadow root doesn't get from the document
  for (const r of rules(base)) {
    if (r.sel.startsWith(".mock") || r.sel.startsWith("html.bare") || r.sel === "body" || r.sel === "html") {
      if (r.sel === "html") shadow.push({media: r.media, sel: ":host", body: "color-scheme:dark"});
      continue;
    }
    if (r.sel === ":root") { shadow.push({...r, sel: ":host", body: r.body.replace(/--mock-h:[^;]*;?/, "").replace(/;\s*$/, "")}); continue; }
    if (LIGHT[r.sel] && !r.media.length) light.push({...r, sel: LIGHT[r.sel]});
    shadow.push(r);
  }
  for (const r of rules(frame)) if (isApp(r.sel)) outer.push(r);
  // the drawing: as it is
  for (const r of rules(draw)) shadow.push(r);
  for (const r of rules(own)) {
    if (r.raw) { shadow.push(r); continue; }
    if (r.sel === ":root") { shadow.push({...r, sel: ":host"}); continue; }
    if (isApp(r.sel)) { outer.push(r); continue; }
    if (LIGHT[r.sel] && !r.media.length) light.push({...r, sel: LIGHT[r.sel]});
    const keep = sels(r.sel).filter(x => !isFrame(x));
    if (!keep.length) continue;
    shadow.push({...r, sel: keep.join(",")});
  }
  if (light.length !== Object.keys(LIGHT).length) fail("the name box's rules (.fld, .sr, :focus-visible) aren't all there");
  // the host fills the frame's fourth row, and the page's .main fills the host
  shadow.unshift({media: [], sel: ":host", body: "display:grid;grid-template-columns:minmax(0,1fr);grid-template-rows:minmax(0,1fr);min-width:0;min-height:0"});
  const SCOPE = "html.bd-page[data-page=hardware] ", HOST = "#sp>";
  const CHEAD = "/* Generated by design/hardware/port.mjs from the Hardware mockup (design/hardware). Don't edit by hand: change the\n   mockup and run it again. */\n";
  write("hardware.css", CHEAD + emit(shadow));
  write("hardware-frame.css", CHEAD + emit([
    ...outer.map(r => ({...r, sel: sels(r.sel).map(x => SCOPE + x).join(",")})),
    ...light.map(r => ({...r, sel: SCOPE + HOST + r.sel}))
  ]));
}
