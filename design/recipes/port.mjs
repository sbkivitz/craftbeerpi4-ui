// Make the recipe pages' mockup (design/recipes) into the recipe pages' own files, untouched where they can be:
//
//   node design/recipes/port.mjs
//
// It writes, under cbpi4gui/src/components/recipes:
//
// - catalog.js: recipes-catalog.js as a module, exporting GROUPS (+ STEP's groups, in brewing order), KINDS (each kind
//   of step's plain name, what it does, its group and its settings in parts), TYPES (each setting's kind of control,
//   as CraftBeerPi declares it) and START (a new step's starting values).
// - recipes.css: the pages' own rules, for their shadow root. The pages draw inside a shadow root so the brew-day
//   screen's rules for .plate, .seg, .note, .main, .steps and the rest (the same names, other things) can't reach them,
//   and their rules can't reach the title bar. So :root becomes :host, and the frame's rules (title bar, last event,
//   tabs, toast: the brew-day screen's own, which it draws) are left out, and so are .app's, which go in
//   recipes-frame.css. A rule for what the pages draw under .app[data-link=lost] is written for .main[data-link=lost],
//   which the page marks the same way.
// - recipes-frame.css: the mockup's .app rules (one screen tall from 620 px, not the brew-day's 860; scrolling below
//   1180 px wide; room for the phone's save bar), for <html data-page=recipes> (the Recipe Book) and
//   <html data-page=brewsteps> (Brew Steps) only.
//
// The stylesheets are kept as text (config-overrides.js), as the brew-day screen's are: the CSS pipeline would
// rewrite them.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "..", "cbpi4gui", "src", "components", "recipes");
const HEAD = "// Generated by design/recipes/port.mjs from the recipe pages' mockup (design/recipes). Don't edit by hand:\n"
  + "// change the mockup and run it again.\n";
const crlf = s => s.replace(/\r\n/g, "\n");
const read = f => crlf(readFileSync(join(here, f), "utf8"));
const fail = msg => { throw new Error(`port.mjs: ${msg} - has the mockup's shape changed?`); };
function between(s, start, end) {
  const i = s.indexOf(start);
  if (i < 0) fail(`no ${JSON.stringify(start)}`);
  const j = s.indexOf(end, i + start.length);
  if (j < 0) fail(`no ${JSON.stringify(end)} after ${JSON.stringify(start)}`);
  return s.slice(i, j);
}
const write = (name, text) => { writeFileSync(join(OUT, name), text); console.log(`wrote ${join(OUT, name)}`); };

/* ---------- catalog.js ---------- */
{
  let js = read("recipes-catalog.js");
  js = js.replace(/^"use strict";\n/m, "");
  const START = "window.CBPI_STEP_CATALOG = (() => {";
  if (js.indexOf(START) < 0) fail("no window.CBPI_STEP_CATALOG = (() => {");
  js = js.replace(START, "const CATALOG = (() => {");
  if (!/\}\)\(\);\s*$/.test(js)) fail("recipes-catalog.js doesn't end with its })();");
  js = js.replace(/\s*$/, "\n") + "export const { GROUPS, KINDS, TYPES, START } = CATALOG;\n";
  for (const n of ["GROUPS", "KINDS", "TYPES", "START"]) if (!new RegExp(`^\\s+${n}: `, "m").test(js)) fail(`no ${n}`);
  write("catalog.js", `${HEAD}${js}`);
}

/* ---------- recipes.css and recipes-frame.css ---------- */
{
  const css = read("recipes.css");
  const FRAME = "/* ---------- the frame:", OWN = "/* ---------- recipes ---------- */";
  if (css.indexOf(FRAME) < 0 || css.indexOf(OWN) < 0) fail("no frame or recipes section");
  const base = css.slice(0, css.indexOf(FRAME));
  const frame = between(css, FRAME, OWN);
  const own = css.slice(css.indexOf(OWN));

  // the rules of a piece of CSS, at the top level or in @media, @supports and @container blocks, nested as they are:
  // [{media: [the blocks' preludes, outermost first], sel, body}]
  function rules(text) {
    const out = [], s = text.replace(/\/\*[\s\S]*?\*\//g, "");
    let i = 0;
    const block = (from, media) => {
      let k = from;
      while (k < s.length) {
        const open = s.indexOf("{", k), close = s.indexOf("}", k);
        if (close >= 0 && (open < 0 || close < open)) return close + 1;
        if (open < 0) return s.length;
        const sel = s.slice(k, open).trim();
        if (/^@(media|supports|container)\b/.test(sel)) { k = block(open + 1, [...media, sel]); continue; }
        if (sel.startsWith("@keyframes")) {
          let depth = 1, p = open + 1;
          while (depth && p < s.length) { if (s[p] === "{") depth++; else if (s[p] === "}") depth--; p++; }
          out.push({media, sel, body: s.slice(open + 1, p - 1), raw: true});
          k = p; continue;
        }
        const end = s.indexOf("}", open);
        out.push({media, sel, body: s.slice(open + 1, end)});
        k = end + 1;
      }
      return k;
    };
    while (i < s.length) i = block(i, []) || s.length;
    return out;
  }
  // the rules again as CSS, each block opened once for the rules in a row that share it
  const emit = list => {
    let out = "", open = [];
    for (const r of list) {
      let same = 0;
      while (same < open.length && same < r.media.length && open[same] === r.media[same]) same++;
      out += "}\n".repeat(open.length - same) + r.media.slice(same).map(m => `${m}{\n`).join("");
      open = r.media;
      out += `${r.sel}{${r.body}}\n`;
    }
    return out + "}\n".repeat(open.length);
  };
  const sels = sel => sel.split(",").map(x => x.trim());
  // the frame's elements: the brew-day screen draws them, with its own rules. The mockup writes layout B's under
  // [data-layout=b], as the brew-day mockup does, some of them in its own section's @media blocks
  const LAYOUT = /^(html)?\[data-layout=b\]\s+/;
  const FRAME_EL = /^(\.app\b(?![^\s]*\s)|\.topbar\b|\.banner\b|\.brand\b|#link-t\b|\.link\b|\.clock\b|\.alloff\b|\.event\b|\.status\b|\.tabs\b|\.toast\b|\.res\b|\.logbtn\b)/;
  const isFrame = x => FRAME_EL.test(x.replace(LAYOUT, ""));
  // .app itself (its grid, height and the phone's room under it), not what the pages draw inside it
  const appOnly = x => /^\.app(\[[^\]]*\])*$/.test(x);
  const isApp = sel => sels(sel).every(appOnly);
  // what the pages draw inside .app: in the shadow root, under the page's own .main, which carries the same marks
  const inApp = x => x.replace(/^\.app((?:\[[^\]]*\])*)\s+/, ".main$1 ");

  const shadow = [], outer = [];
  // base: the page's element defaults, which a shadow root doesn't get from the document
  for (const r of rules(base)) {
    if (r.sel.startsWith(".mock") || r.sel.startsWith("html.bare") || r.sel === "body" || r.sel === "html") {
      if (r.sel === "html") shadow.push({media: r.media, sel: ":host", body: "color-scheme:dark"});
      continue;
    }
    if (r.sel === ":root") { shadow.push({...r, sel: ":host", body: r.body.replace(/--mock-h:[^;]*;?/, "").replace(/;\s*$/, "")}); continue; }
    shadow.push(r);
  }
  for (const r of rules(frame)) if (isApp(r.sel)) outer.push(r);
  for (const r of rules(own)) {
    if (r.raw) { shadow.push(r); continue; }
    if (r.sel === ":root") { shadow.push({...r, sel: ":host"}); continue; }
    if (isApp(r.sel)) { outer.push(r); continue; }
    const keep = sels(r.sel).filter(x => !isFrame(x)).map(inApp);
    if (!keep.length) continue;
    shadow.push({...r, sel: keep.join(",")});
  }
  if (!outer.length) fail("no .app rules");
  // the host fills the frame's fourth row, and the page's .main fills the host
  shadow.unshift({media: [], sel: ":host", body: "display:grid;grid-template-columns:minmax(0,1fr);grid-template-rows:minmax(0,1fr);min-width:0;min-height:0"});
  // the Recipe Book's frame (page "recipes") and Brew Steps' (page "brewsteps"): the same rules
  const SCOPES = ["html.bd-page[data-page=recipes] ", "html.bd-page[data-page=brewsteps] "];
  const CHEAD = "/* Generated by design/recipes/port.mjs from the recipe pages' mockup (design/recipes). Don't edit by hand:\n   change the mockup and run it again. */\n";
  write("recipes.css", CHEAD + emit(shadow));
  write("recipes-frame.css", CHEAD + emit(outer.map(r => ({...r, sel: SCOPES.flatMap(p => sels(r.sel).map(x => p + x)).join(",")}))));
}
